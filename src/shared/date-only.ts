/** True when a value is a real Gregorian calendar date in YYYY-MM-DD form. */
export function isDateOnly(value: string): boolean {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value)
  if (!match) return false

  const year = Number(match[1])
  const month = Number(match[2])
  const day = Number(match[3])
  if (year < 1 || month < 1 || month > 12 || day < 1) return false

  const leapYear = year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0)
  const daysInMonth = [31, leapYear ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
  return day <= daysInMonth[month - 1]
}

export function assertDateOnly(value: string, label = 'date'): string {
  if (!isDateOnly(value)) throw new Error(`Use a real calendar ${label} in YYYY-MM-DD format.`)
  return value
}
